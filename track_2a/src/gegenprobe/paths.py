"""Filesystem layout. Everything committed lives under ROOT (track_2a/); large or derived-from-network material lives under
WORK (gitignored, default track_2a/.work) and is never committed.

Env overrides:
  GP_WORK      work/cache dir (exports, PDFs, extracted texts)
  GP_OPD_RAW   directory holding the single-file OPD exports (affairs/events/agendas/bodies/contributors .ndjson.gz)
  GP_DOCS_META directory holding part*/docs_meta.jsonl.gz and texts_meta.jsonl.gz (output of census.scan)
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # track_2a/
DATA = ROOT / "data"                                 # committed, <= 100 MB
RESULTS = ROOT / "results"                           # committed, generated by code; every claim points here
DOCS = ROOT / "docs"
PROMPTS = ROOT / "src" / "prompts"
EVAL = ROOT / "eval"
WORK = Path(os.environ.get("GP_WORK", ROOT / ".work"))
OPD_RAW = Path(os.environ.get("GP_OPD_RAW", WORK / "opd"))
DOCS_META = Path(os.environ.get("GP_DOCS_META", WORK / "docs_meta"))
PDF_CACHE = WORK / "pdf"       # <sha256>.pdf
TEXT_CACHE = WORK / "text"     # <sha256>.<extractor>.json  (pages + extractor version)
MODEL_CACHE = DATA / "model_cache"   # committed: hash-keyed model outputs, replayed by `make run`


def ensure(*dirs: Path) -> None:
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)
