"""Writes schema/gegenprobe_schema.py: schema v0.1 as one side-effect-free module for integrators.

    python -m gegenprobe.schema.standalone            write track_2a/schema/gegenprobe_schema.py
    python -m gegenprobe.schema.standalone --check    exit 1 if the committed file differs from what would be written

`import gegenprobe.schema.public` imports the gegenprobe package, whose __init__ installs the I/O hardening (timeouts,
size caps) and pulls in more modules; `pip install` of the package also puts a .pth into site-packages. An extraction
workbench only needs the models. The generated file is the frozen src/gegenprobe/schema/schema_v0_1.py (LOCK5) byte for
byte, plus the helpers of schema/public.py (json_schema with $schema/$id/version, validate_affair,
validate_doc_extraction). It imports only the standard library and pydantic, and it reads and writes nothing.
tests/test_standalone_schema.py checks that its JSON Schemas equal gegenprobe.schema.public.json_schema and the committed
results/schema/*.schema.json, and that it loads in an isolated interpreter without importing gegenprobe.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

from ..paths import ROOT
from .public import ID_BASE

SRC = Path(__file__).with_name("schema_v0_1.py")
OUT = ROOT / "schema" / "gegenprobe_schema.py"

TAIL = '''

# ------------------------------------------------------------------------------------------------- standalone additions
# The same helpers as gegenprobe/schema/public.py, so a workbench needs only this file and pydantic.
ID_BASE = {id_base!r}
SCHEMA_IDS = {{"affair": ID_BASE + "affair.schema.json", "doc_extraction": ID_BASE + "doc_extraction.schema.json"}}


def json_schema(name: str) -> dict:
    """JSON Schema of `affair` or `doc_extraction`, identified: $schema, $id, version first, then Pydantic's schema."""
    body = {{"affair": Affair, "doc_extraction": DocExtraction}}[name].model_json_schema()
    return {{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_IDS[name], "version": SCHEMA_VERSION,
            **body}}


def validate_affair(obj: dict) -> Affair:
    return Affair.model_validate(obj)


def validate_doc_extraction(obj: dict) -> DocExtraction:
    return DocExtraction.model_validate(obj)
'''


def render() -> str:
    src = SRC.read_text(encoding="utf-8")
    sha = hashlib.sha256(src.encode("utf-8")).hexdigest()
    head = ("# GENERATED by `python -m gegenprobe.schema.standalone`: do not edit. Schema v0.1 of a Swiss parliamentary affair\n"
            "# as one module: track_2a/src/gegenprobe/schema/schema_v0_1.py (frozen, sha256\n"
            f"# {sha}) verbatim, then the helpers of gegenprobe/schema/public.py.\n"
            "# Needs only pydantic>=2 (no gegenprobe package, no .pth, no I/O): copy this file next to your code and\n"
            "#   from gegenprobe_schema import Affair, DocExtraction, TypedNull, json_schema, validate_doc_extraction\n"
            "# Docs: track_2a/docs/schema.md.\n")
    return head + src.rstrip("\n") + "\n" + TAIL.format(id_base=ID_BASE)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(f"{OUT}: {'current' if same else 'STALE (run python -m gegenprobe.schema.standalone)'}")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
