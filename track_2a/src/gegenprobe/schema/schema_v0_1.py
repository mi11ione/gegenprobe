"""Gegenprobe affair schema v0.1.0: a middle layer for Swiss parliamentary affairs (what JATS is for journal articles).

Design rules
  * Every value that comes from a document or from OPD metadata is a `Valued[T]` carrying its provenance; every value that
    could not be established is a `TypedNull` that says *why* (null_reason). There is no bare `None` for an extractable field.
  * `basis` separates what the source says from what we derived (challenge ethics clause: "clearly distinguish extracted
    content from generated/inferred content"):
        extracted   the value string occurs verbatim at (doc, page, char_start, char_end)
        normalised  the span is verbatim, the value is its normal form (e.g. "28. August 2024" -> 2024-08-28)
        metadata    taken from a structured OPD/canton field (`source` names the record)
        inferred    a classification derived from a cited span (e.g. a government recommendation enum)
  * `route` records which stage of the converter decided: metadata | rule | apertus | ocr+rule | ocr+apertus.
    Apertus-decided values and abstentions carry model_build, theta and margin, so a reviewer can see how close the call was.
  * Document content (tables, annexes, images, stamps) is referenced by page range, not re-extracted.

Vocabularies are Python Literals here (single source of truth); data/schema/*.json carries their multilingual labels, the
OPD harmonised ids they map from and corpus counts (generated by `python -m gegenprobe.schema.vocab`).
"""
from __future__ import annotations

import datetime as dt
from typing import Annotated, Generic, Literal, TypeVar, Union

from pydantic import BaseModel, ConfigDict, Discriminator, Field, model_validator

SCHEMA_VERSION = "0.1.0"

# ----------------------------------------------------------------------------------------------- controlled vocabularies
Route = Literal["metadata", "rule", "apertus", "ocr+rule", "ocr+apertus"]
MODEL_ROUTES = ("apertus", "ocr+apertus")
SPAN_ROUTES = ("rule", "apertus", "ocr+rule", "ocr+apertus")
Basis = Literal["extracted", "normalised", "metadata", "inferred"]
NullReason = Literal["not_in_corpus", "unlinked", "text_failed", "image_only", "oral", "present_unanchored", "not_applicable",
                     "not_in_document"]
# which routes may produce which null reason (a model can only abstain on a document it read)
NULL_ROUTES: dict[str, tuple[str, ...]] = {
    "not_in_corpus": ("metadata", "rule", "apertus", "ocr+rule", "ocr+apertus"),
    "unlinked": ("metadata",),
    "text_failed": ("metadata", "rule"),
    "image_only": ("metadata", "rule"),
    "oral": ("metadata", "rule", "ocr+rule"),
    "present_unanchored": ("rule", "apertus", "ocr+rule", "ocr+apertus"),
    "not_applicable": ("metadata", "rule"),
    # document-level: this document was read (by rules or the model) and the value is not in it. Affair-level absence needs
    # the census/repair join and is not_in_corpus / unlinked instead.
    "not_in_document": ("rule", "apertus", "ocr+rule", "ocr+apertus"),
}
AnswerLinkStatus = Literal["attached", "agenda", "parentless", "absent", "image_only", "oral", "not_applicable"]
AffairType = Literal[
    "motion", "postulate", "interpellation", "question", "question_time", "parliamentary_initiative", "cantonal_initiative",
    "popular_initiative", "government_affair", "petition", "consultation", "election", "amendment", "naturalisation",
    "report", "information_document", "approval_decision", "budget", "miscellaneous", "unknown",
]
DateRole = Literal[
    "submitted", "answer_decided", "answer_dispatched", "answered", "scheduled", "debated", "referred_to_committee",
    "decided", "closed", "withdrawn", "published", "entry_into_force", "deadline", "referendum_deadline", "popular_vote",
    "other",
]
ActorRole = Literal[
    "submitter", "co_signatory", "first_signatory", "on_behalf_of_group", "addressed_body", "answering_body",
    "executive_signatory", "presiding_officer", "secretary", "committee", "committee_member", "rapporteur",
    "referenced_member", "roll_call_voter", "other",
]
ActorKind = Literal["person", "parliamentary_group", "party", "committee", "executive", "parliament", "administration",
                    "public", "other"]
ProceduralState = Literal["submitted", "pending_answer", "answered", "scheduled", "in_committee", "debated", "referred",
                          "decided", "closed", "withdrawn", "lapsed", "unknown"]
DecisionOutcome = Literal["adopted", "rejected", "referred", "converted_to_postulate", "partially_adopted", "written_off",
                          "not_written_off", "acknowledged", "withdrawn", "lapsed", "returned", "no_decision", "pending"]
GovRecommendation = Literal["accept", "reject", "convert", "partial", "accept_and_write_off", "none", "not_applicable"]
Level = Literal["federal", "cantonal", "communal"]
Lang = Literal["de", "fr", "it", "rm", "en"]
DocRole = Literal["question", "answer", "decision", "message", "report", "minutes", "agenda", "annex", "publication",
                  "placeholder", "other"]
DocSource = Literal["opd", "canton", "commune", "fedlex", "curia_vista", "other"]
PartKind = Literal["table", "annex", "image", "signature", "stamp", "handwriting", "header", "footer", "budget_table", "toc"]
Relation = Literal["answers", "answered_by", "follows_up", "replaces", "replaced_by", "joined_with", "same_subject",
                   "cites", "implements", "counter_proposal_to", "other"]

T = TypeVar("T")
_strict = ConfigDict(extra="forbid")


# ----------------------------------------------------------------------------------------------- provenance-bearing values
class Valued(BaseModel, Generic[T]):
    """A value with provenance. Span fields point into the cached text of `doc` (pages[page-1][char_start:char_end])."""
    model_config = _strict
    kind: Literal["value"] = "value"
    value: T
    role: str | None = Field(None, description="semantic role of the value (e.g. a DateRole for dates)")
    basis: Basis
    route: Route
    doc: str | None = Field(None, description="Document.doc_id the span points into")
    page: int | None = Field(None, ge=1)
    char_start: int | None = Field(None, ge=0)
    char_end: int | None = Field(None, ge=0)
    quote: str | None = Field(None, max_length=400, description="verbatim source text at the span (short)")
    context: str | None = Field(None, max_length=400, description="the source line around the span, for review (not checked)")
    source: str | None = Field(None, description="structured record for basis=metadata, e.g. 'opd:events/618276'")
    model_build: str | None = None
    theta: float | None = None
    margin: float | None = Field(None, description="null margin of the forced choice (nats); value kept iff margin <= theta")
    candidates: int | None = Field(None, ge=0, description="size of the closed candidate set the model chose from")
    rule: str | None = Field(None, description="id of the deterministic rule that produced the value (route rule / ocr+rule)")

    @model_validator(mode="after")
    def _consistent(self):
        has_span = self.page is not None and self.char_start is not None and self.char_end is not None
        # a closed-set classification by the model over the whole document (e.g. a recommendation enum) has no single span:
        # it must name the document and the size of the closed set it chose from
        doc_level = self.basis == "inferred" and self.route in MODEL_ROUTES and not has_span
        if doc_level:
            if not (self.doc and self.candidates):
                raise ValueError("a document-level model classification needs doc and candidates")
        elif self.basis in ("extracted", "normalised", "inferred") or self.route in SPAN_ROUTES:
            if not (has_span and self.doc and self.quote):
                raise ValueError(f"route={self.route} basis={self.basis} needs doc, page, char_start, char_end and quote")
        if has_span and self.char_end <= self.char_start:
            raise ValueError("char_end must be > char_start")
        if self.basis == "metadata" and not self.source:
            raise ValueError("basis=metadata needs `source` (the OPD/canton record)")
        if self.route == "metadata" and self.basis not in ("metadata",):
            raise ValueError("route=metadata implies basis=metadata")
        if self.basis == "metadata" and self.route != "metadata":
            raise ValueError("basis=metadata implies route=metadata")
        _model_fields(self.route, self.model_build, self.theta, self.margin)
        return self


class TypedNull(BaseModel):
    """An explicit, typed absence. A converter never returns a bare None for a field it was asked to fill."""
    model_config = _strict
    kind: Literal["null"] = "null"
    null_reason: NullReason
    role: str | None = None
    route: Route
    evidence: str = Field(..., min_length=1, description="why: the record, rule or abstention that established the null")
    doc: str | None = None
    related_doc: str | None = Field(None, description="for unlinked: the OPD doc that holds the value but is not attached")
    model_build: str | None = None
    theta: float | None = None
    margin: float | None = None

    @model_validator(mode="after")
    def _consistent(self):
        allowed = NULL_ROUTES[self.null_reason]
        if self.route not in allowed:
            raise ValueError(f"null_reason={self.null_reason} cannot come from route={self.route} (allowed: {allowed})")
        if self.null_reason == "unlinked" and not self.related_doc:
            raise ValueError("null_reason=unlinked needs related_doc (the unattached document)")
        _model_fields(self.route, self.model_build, self.theta, self.margin)
        if self.route in MODEL_ROUTES and self.margin is not None and self.theta is not None and self.margin <= self.theta:
            raise ValueError("a model abstention needs margin > theta")
        return self


def _model_fields(route, build, theta, margin):
    if route in MODEL_ROUTES:
        if build is None or theta is None or margin is None:
            raise ValueError(f"route={route} needs model_build, theta and margin")
    elif any(v is not None for v in (build, theta, margin)):
        raise ValueError(f"route={route} must not carry model_build/theta/margin")


class DateValue(Valued[dt.date]):
    """An ISO date with provenance (basis=normalised when read from a span like '28. August 2024')."""
    decision_number: str | None = Field(
        None, description="the executive's decision number printed with the date (RRB-Nr., ACE, RG n.), if the rule captured it")


class TextValue(Valued[str]):
    pass


class ProceduralStateValue(Valued[ProceduralState]):
    pass


class DecisionValue(Valued[DecisionOutcome]):
    pass


class GovRecommendationValue(Valued[GovRecommendation]):
    pass


def _f(cls):
    return Annotated[Union[cls, TypedNull], Discriminator("kind")]


DateF = _f(DateValue)
StrF = _f(TextValue)
ProceduralStateF = _f(ProceduralStateValue)
DecisionF = _f(DecisionValue)
GovRecommendationF = _f(GovRecommendationValue)


# ----------------------------------------------------------------------------------------------- documents
class DocumentPart(BaseModel):
    model_config = _strict
    kind: PartKind
    page_from: int = Field(..., ge=1)
    page_to: int = Field(..., ge=1)
    label: str | None = Field(None, max_length=200)

    @model_validator(mode="after")
    def _order(self):
        if self.page_to < self.page_from:
            raise ValueError("page_to < page_from")
        return self


class Document(BaseModel):
    model_config = _strict
    doc_id: str = Field(..., description="stable id, e.g. 'opd:404590', 'be-ogd:0778ef86...', 'fedlex:eli/fga/2014/2095/de'")
    source: DocSource
    url: str | None = None
    sha256: str | None = Field(None, pattern=r"^[0-9a-f]{64}$")
    role: DocRole
    language: Lang | Literal["unspecified"] | None = Field(
        None, description="'unspecified' = the source records no language (OPD's empty field); None = not known to us")
    n_pages: int | None = Field(None, ge=0)
    extractor: str | None = Field(None, description="pdftotext-<ver> | tesseract-<ver>-<langs> | opd-text")
    image_only: bool = False
    opd_text_status: Literal["ok", "null", "blank", "failed", "placeholder"] | None = None
    parts: list[DocumentPart] = []


