# ruff: noqa: E501  (prose templates)
"""Rewrite the generated results section of docs/census.md from results/census/*.json (no hand-typed numbers).

usage: python -m gegenprobe.census.doc
"""

from __future__ import annotations

import json

from ..paths import DOCS
from .funnel import OUT

BEGIN, END = "<!-- BEGIN GENERATED: census results -->", "<!-- END GENERATED: census results -->"
LABEL = {
    "type": "type",
    "submitter": "submitter",
    "co_signatories": "co-signatories",
    "addressed_body": "addressed body (department)",
    "qa_pairing": "question/answer pairing",
    "date_submission": "date: submission",
    "date_answer": "date: answer",
    "date_dispatch": "date: dispatch",
    "date_decision": "date: decision",
    "decision_outcome": "decision outcome",
    "government_recommendation": "government recommendation",
    "procedural_state": "procedural state (state field)",
    "procedural_history": "procedural history (harmonised events)",
    "related_affairs": "related affairs",
    "answer_link_status": "answer-link status (new)",
    "language": "language (documents)",
    "documents_usable_text": "documents with usable text",
}


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def render() -> str:
    m = json.loads((OUT / "matrix.json").read_text())
    s = json.loads((OUT / "summary.json").read_text())
    q = json.loads((OUT / "question.json").read_text())
    fnd = json.loads((OUT / "findings.json").read_text())["findings"]
    vr = json.loads((OUT / "vs_reconcile.json").read_text())
    rep = json.loads((OUT / "spike_reproduction.json").read_text()) if (OUT / "spike_reproduction.json").exists() else None
    L = [BEGIN, "", "## 4. Results (generated by `python -m gegenprobe.census.doc`)", ""]
    n = s["national"]
    L += [
        f"**Funnel.** {n['n']:,} in-scope affairs in {s['n_bodies_in_scope']} bodies; {n['ev_answer']:,} with a written-answer "
        f"event; **{n['gap']:,} ({pct(s['national_gap_share'])}) without answer text**; {n['gap_after_agenda_join']:,} after "
        f"the in-corpus agenda join ({s['agenda_rejoin_in_gap']:,} re-joined). 2024–25: {s['national_2024_25']['gap']:,} "
        f"({pct(s['national_2024_25_gap_share'])}).",
        "",
    ]
    if rep:
        L += [
            f"**Reproduction.** The ported funnel reproduces the 8 Oct spike cell for cell: {rep['cells_ours']:,} body × type × "
            f"year cells, {rep['field_differences']} differing values, document-status table identical: {rep['docstat_identical']}.",
            "",
        ]
    ls = s["link_status"]
    g = s["gap_prime_decomposition"]
    L += [
        "**Answer-link status** (all in-scope affairs): "
        + ", ".join(f"`{k}` {v:,}" for k, v in ls.items())
        + f". Of gap′: BE {g['BE']:,} (canton lists an answer for {s['be_gap_prime']['source_has_answer']:,}; "
        f"{s['be_gap_prime']['parentless']:,} relinkable parentless documents), CHE {g['CHE']}, other bodies with an answer document "
        f"but no text {g['other_doc_present_no_text']:,} (of which VS oral stubs {g['other_vs_oral_stub']:,} by the length proxy; {vr['canonical']['value']:,} by the exact text rule that the repair list uses, `results/census/vs_reconcile.json`), other bodies with no "
        f"answer document {g['other_no_answer_doc']:,}.",
        "",
        "### Field-tier table",
        "",
        "Status counts are over eligible bodies (≥ 20 applicable affairs). `meta`/`doc` are pooled over applicable affairs.",
        "",
        "| field | tier | bodies | metadata | mixed | pdf | no source | meta (pooled) | usable doc (pooled) | route if not in metadata |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k, f in m["fields"].items():
        c = f["status_counts"]
        L.append(
            f"| {LABEL[k]} | **{f['tier']}** | {f['eligible_bodies']} | {c['metadata']} | {c['mixed']} | {c['pdf']} | "
            f"{c['no_source']} | {pct(f['pooled_meta'])} | {pct(f['pooled_doc'])} | {f['extraction_route']} |"
        )
    L += [""]
    for k, f in m["fields"].items():
        if f["note"]:
            L.append(f"- *{LABEL[k]}*: {f['note']}.")
    tc = m["tier_counts"]
    L += [
        "",
        f"**Verdict by the pre-declared rule:** {tc['feasible']} fields feasible, {tc['partial']} partial, "
        f"{tc['fundamentally different']} fundamentally different. No field lacks a written source in ≥ 20% of parliaments; "
        "what varies is where the value lives (metadata in some bodies, only in PDFs in others) and the vocabulary.",
        "",
        "### Where the concept itself differs (post hoc, descriptive; does not change tiers)",
        "",
    ]
    cs = m["concept_split"]
    for t, v in cs["answer_modality_by_type"].items():
        L.append(f"- {t}: {v['oral']:,} of {v['with_answer']:,} answered affairs have only an oral answer ({pct(v['oral_share'])}).")
    L += [
        f"- VS files {vr['canonical']['value']:,} oral answers as an `_ANT` stub document, not as an oral event (exact text rule; "
        f"the census length proxy flags {cs['vs_oral_stub_affairs']:,}: proxy precision {100 * vr['doc_level']['proxy_precision']:.1f}% "
        f"per document, recall {100 * vr['doc_level']['proxy_recall']:.1f}%, `results/census/vs_reconcile.json`).",
        f"- In {q['n_same_day_bodies']} of {q['n_bodies']} bodies the 'answer' event date equals the submission date for ≥ 50% of "
        "affairs: the date exists in metadata but is not an answer date ("
        + ", ".join(f"{b['name']} {pct(b['same_day_share'])}" for b in q["same_day_bodies"])
        + ").",
        "",
        "Cited evidence (not recomputed; `data/census/cited_evidence.json`): the S3-BILANZ atom inventory over 12 bodies left "
        f"{pct(m['cited_evidence']['booking']['suspense_share'])} of atoms without a schema account; five gaps recur across bodies "
        "and languages: " + "; ".join(x["gap"] for x in m["cited_evidence"]["schema_gaps"]) + ". Estimating the *size* of the "
        f"missing schema with Chao2 failed both pre-registered checks (no saturation, ≈{m['cited_evidence']['chao2']['new_accounts_per_body_mean']} "
        "new accounts per body): a well-evidenced negative.",
        "",
        "### The cross-parliamentary question",
        "",
        f"Across {q['n_bodies']} parliaments with ≥ {q['min_written']} written-answer interventions, the answer text is in OPD for "
        f"{pct(q['national']['text_share_now'])} ({pct(q['national']['text_share_after_relink'])} after the measured relinks); "
        f"the median time from submission to the answer event is {q['national']['median_days']:.0f} days "
        f"(Question time {q['by_type']['Question time']['median_days']:.0f}). Lowest answer-text shares: "
        + ", ".join(f"{b['name']} {pct(b['text_share_now'])}" for b in q["lowest_text_share"][:6])
        + ". Caveat: " + q["caveats"][0],
        "",
        "### Data-quality findings",
        "",
        "| finding | value | verified |",
        "|---|---|---|",
    ]
    for f in fnd:
        val = f.get("share")
        v = (
            f"{f['count']:,} / {f['denominator']:,} ({pct(val)})"
            if val is not None
            else (f"{f['count']:,}" + (f" / {f['denominator']:,}" if f.get("denominator") else ""))
            if "count" in f
            else json.dumps(f.get("value"), ensure_ascii=False)
        )
        if f["id"] == "be_begin_date_import":
            v += f"; {f['on_2024_10_28']:,} on 2024-10-28"
        L.append(f"| {f['statement']} | {v} | {f['verified']} |")
    L += [
        "",
        "## 5. Known limitations",
        "",
        "- The answer patterns are hand-written regexes; their precision is checked only through the 40-affair gap audit "
        "(27/35 true gaps) and the BE canton join (spikes/recovery).",
        "- `be_rrb_filled` (scan-time flag) expects the year first; the current BE format \"RRB-Nr.: 879/2024\" is not flagged. "
        "BE answers are still found by name/heading; the flag is kept frozen because changing it needs a re-scan.",
        "- Year comes from the affair number where it starts with a year, else from `begin_date` (affected by the BE 2024-10-28 "
        "import date).",
        "- Parentless counts do not check `news_id` (not kept by the scan).",
        "- `co-signatories` is a lower bound (no co-signers vs. unrecorded is indistinguishable in metadata).",
        "- The `accuracy` column stays empty: measured extraction accuracy exists only for the answer date, per language x level "
        "cell of the held-out gold set rather than per body (`results/census/matrix_accuracy.json`; no federal documents in the "
        "gold set). `pdf` cells say a converter *can* "
        "work there, not that it does.",
        "",
        END,
    ]
    return "\n".join(L)


def main() -> None:
    p = DOCS / "census.md"
    t = p.read_text()
    new = render()
    if BEGIN in t:
        t = t[: t.index(BEGIN)] + new + t[t.index(END) + len(END) :]
    else:
        t = t.rstrip() + "\n\n" + new + "\n"
    p.write_text(t)


if __name__ == "__main__":
    main()
